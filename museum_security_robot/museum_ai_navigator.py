# 5. OPERATOR INTERFACES
# ===========================================================================

BANNER = """
=====================================================================
  MUSEUM SECURITY ROBOT - AI COMMAND CONSOLE
=====================================================================
  Speak to it in plain English. Some things to try:

    I think someone is messing with the servers
    Did I leave my backpack near the old bones?
    There's a kid climbing on the marble figure
    Check where people eat, someone reported a spill
    Somebody just walked in the front door
    Is anyone trying to sneak out the back?
    Head back to the monitoring station
    Sweep the west half of the building
    Do a full round of the museum
    Where are you right now?

  Commands:  list | menu | exit
=====================================================================
"""


def menu_mode(patrol):
    """Numbered semantic-location menu - the non-LLM control path.

    The project brief asks for a menu program that lists predefined semantic
    locations and publishes the matching goal pose. This is that, and it also
    gives you a working demo if the network or API key fails on demo day.
    """
    names = list(patrol.locations)
    while True:
        print("\n--- MUSEUM NAVIGATION MENU ---")
        for i, n in enumerate(names, 1):
            print(f"  {i}. {n:<22} {patrol.locations[n]['description']}")
        print("  0. exit")
        raw = input("select > ").strip()
        if raw in ("0", "exit", "quit"):
            return
        if not raw.isdigit() or not 1 <= int(raw) <= len(names):
            print("invalid selection")
            continue
        patrol.go(names[int(raw) - 1])


def ai_mode(patrol, brain):
    print(BANNER)
    while True:
        try:
            text = input("Commander > ").strip()
        except EOFError:
            return
        if not text:
            continue
        low = text.lower()
        if low in ("exit", "quit"):
            return
        if low == "menu":
            menu_mode(patrol)
            continue
        if low == "list":
            for n, l in patrol.locations.items():
                print(f"  {n:<22} {l['description']}")
            continue

        print("[ai] thinking...")
        decision = brain.interpret(text)
        if decision is None:
            # Explicit, loud, and does NOT move the robot.
            print("[ai] >>> LLM UNAVAILABLE - no action taken. "
                  "Use 'menu' to drive manually. <<<\n")
            continue
        dispatch(patrol, *decision)


# ===========================================================================
# 6. ENTRY POINT
# ===========================================================================

def main(argv=None):
    ap = argparse.ArgumentParser(description="Museum security robot commander")
    ap.add_argument("--menu", action="store_true",
                    help="numbered location menu, no LLM required")
    ap.add_argument("--goto", metavar="LOCATION",
                    help="drive to one location and exit (for scripted demos)")
    ap.add_argument("--patrol", action="store_true",
                    help="run a full circuit of every location and exit")
    ap.add_argument("--no-initial-pose", action="store_true",
                    help="skip setInitialPose (use if you set it in RViz)")
    ap.add_argument("--model", default="gemini-3.5-flash")
    args, ros_args = ap.parse_known_args(argv if argv is not None else sys.argv[1:])

    rclpy.init(args=ros_args)
    locations, spawn = load_locations()
    patrol = SecurityPatrol(locations, spawn)

    try:
        patrol.start(set_initial_pose=not args.no_initial_pose)

        if args.goto:
            if args.goto not in locations:
                print(f"unknown location '{args.goto}'. "
                      f"Known: {', '.join(locations)}")
            else:
                patrol.go(args.goto)
        elif args.patrol:
            patrol.patrol(list(locations))
        elif args.menu:
            menu_mode(patrol)
        else:
            brain = MuseumBrain(locations, model=args.model)
            if not brain.available:
                print("Falling back to the manual menu.\n")
                menu_mode(patrol)
            else:
                ai_mode(patrol, brain)
    except KeyboardInterrupt:
        print("\ninterrupted")
    finally:
        patrol.shutdown()
        rclpy.shutdown()


if __name__ == "__main__":
    main()
